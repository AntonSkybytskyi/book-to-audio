import { describe, expect, it } from "vitest";
import { prepareRussian } from "./russian.js";

const check = (cases: readonly (readonly [string, string])[]) =>
  it.each(cases)("%j", (text, expected) => {
    expect(prepareRussian(text)).toBe(expected);
  });

// What espeak-ng gets wrong in Russian is declined here; its plain numbers are left as digits.
describe("Russian years and dates", () => {
  check([
    ["В 1999 году был.", "В тысяча девятьсот девяносто девятом году был."],
    ["в 1812 г. была", "в тысяча восемьсот двенадцатом году была"],
    ["до 1861 г.", "до тысяча восемьсот шестьдесят первого года."],
    ["к 1900 г.", "к тысяча девятисотому году."],
    ["к 1900 году", "к тысяча девятисотому году"],
    [
      "с 1799 по 1837 г.",
      "с тысяча семьсот девяносто девятого года по тысяча восемьсот тридцать седьмой год.",
    ],
    ["3 июня 1799 г.", "третьего июня тысяча семьсот девяносто девятого года."],
    ["Это 1861 год", "Это тысяча восемьсот шестьдесят первый год"],
    ["3 июня", "третьего июня"],
    ["31 декабря", "тридцать первого декабря"],
  ]);

  it("leaves an abbreviation whose case cannot be told", () => {
    expect(prepareRussian("Тогда 1812 г. продолжился.")).toBe("Тогда 1812 г. продолжился.");
  });
});

describe("Russian centuries and chapters", () => {
  check([
    ["XIX век", "девятнадцатый век"],
    ["в XIX веке", "в девятнадцатом веке"],
    ["до XX в.", "до двадцатого века."],
    ["в XIX в.", "в девятнадцатом веке."],
    [
      "Это конец XIX в. и начало XX века.",
      "Это конец девятнадцатого века и начало двадцатого века.",
    ],
    ["в начале XX века", "в начале двадцатого века"],
    ["Глава IV", "Глава четвёртая"],
    ["глава XII.", "глава двенадцатая."],
    ["в главе IV", "в главе четвёртой"],
    ["Часть II", "Часть вторая"],
    ["Он читал часть II", "Он читал часть II"], // "часть" is also an accusative: only at a paragraph start
    ["IV", "4"],
    ["XII.", "12."],
  ]);
});

describe("Russian quantities", () => {
  check([
    ["15%", "15 процентов"],
    ["1%", "1 процент"],
    ["21%", "21 процент"],
    ["3,5%", "3,5 процента"],
    ["5 руб.", "5 рублей."],
    ["21 коп.", "двадцать одна копейка."],
    ["12,50 руб.", "12 рублей 50 копеек."],
    ["$5", "5 долларов"],
    ["100 €", "100 евро"],
    ["1 000 000", "1000000"],
    ["10:30", "10:30"],
  ]);
});

describe("Russian ordinals written with an ending", () => {
  check([
    ["21-й век", "двадцать первый век"],
    ["3-го", "третьего"],
    ["3-му", "третьему"],
    ["в 3-м классе", "в третьем классе"],
    ["с 3-м", "с третьим"],
    ["5-я", "пятая"],
    ["с 3-й попытки", "с третьей попытки"],
    ["идёт 3-м", "идёт 3-м"], // "-м" after no preposition
  ]);
});

describe("Russian agreement of 1 and 2", () => {
  check([
    ["21 яблоко", "двадцать одно яблоко"],
    ["1 книга", "одна книга"],
    ["2 книги", "две книги"],
    ["3 книги", "3 книги"],
    ["1 мужчина", "1 мужчина"],
    ["21 стол", "21 стол"],
  ]);
});

describe("Russian abbreviations", () => {
  check([
    ["и т. д.", "и так далее."],
    ["Так и т. п. Дальше.", "Так и тому подобное. Дальше."],
    ["Т. е. так", "То есть так"],
    ["т. к. поздно", "так как поздно"],
    ["см. рис. 3", "смотри рисунок 3"],
    ["на рис. 3", "на рисунке 3"],
    ["5 см.", "5 см."],
    ["г. Москва", "город Москва"],
    ["в г. Москве", "в городе Москве"],
    ["им. Пушкина", "им. Пушкина"],
    ["школа им. Пушкина", "школа имени Пушкина"],
    ["А. С. Пушкин", "А. С. Пушкин"],
  ]);
});
