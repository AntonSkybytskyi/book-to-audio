import { createNumerals, withEnding, type Endings } from "./numerals.js";

// "-ый" and the stressed "-ой" (второй, шестой, седьмой, восьмой, сороковой) share their endings.
const HARD: Endings = {
  m: ["ый", "ого", "ому", "ый", "ым", "ом"],
  f: ["ая", "ой", "ой", "ую", "ой", "ой"],
  n: ["ое", "ого", "ому", "ое", "ым", "ом"],
  p: ["ые", "ых", "ым", "ые", "ыми", "ых"],
};
const STRESSED: Endings = { ...HARD, m: ["ой", "ого", "ому", "ой", "ым", "ом"] };
// Only "третий" declines this way.
const SOFT: Endings = {
  m: ["ий", "ьего", "ьему", "ий", "ьим", "ьем"],
  f: ["ья", "ьей", "ьей", "ью", "ьей", "ьей"],
  n: ["ье", "ьего", "ьему", "ье", "ьим", "ьем"],
  p: ["ьи", "ьих", "ьим", "ьи", "ьими", "ьих"],
};

