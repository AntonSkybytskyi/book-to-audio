/**
 * Abbreviations that end in a dot without ending the sentence, per language: lowercase, no space
 * after an inner dot ("т.д"), no final dot. Entries with a space are matched with the space.
 */
export interface SentenceAbbreviations {
  /** The dot never ends a sentence ("Mr.", "ім."). */
  inside: ReadonlySet<string>;
  /** The dot ends the sentence when a capital letter follows ("etc.", "т. д."). */
  mayEnd: ReadonlySet<string>;
  /** The dot belongs to a number that follows: "No. 5", "р. 12". */
  beforeNumber: ReadonlySet<string>;
}

