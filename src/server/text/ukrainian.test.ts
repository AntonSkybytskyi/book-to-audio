import { describe, expect, it } from "vitest";
import { prepareUkrainian } from "./ukrainian.js";

const check = (cases: readonly (readonly [string, string])[]) =>
  it.each(cases)("%j", (text, expected) => {
    expect(prepareUkrainian(text)).toBe(expected);
  });

// The voice reads letters: digits and Latin letters would be dropped, so everything is words.
describe("Ukrainian years and dates", () => {
  check([
    ["У 1999 році був.", "У тисяча дев'ятсот дев'яносто дев'ятому році був."],
    ["до 1861 року", "до тисяча вісімсот шістдесят першого року"],
    ["Це 1861 рік", "Це тисяча вісімсот шістдесят перший рік"],
    ["Народився 1814 р. у селі.", "Народився тисяча вісімсот чотирнадцятого року у селі."],
    ["в 2005 році", "в дві тисячі п'ятому році"],
    ["У 2000 році", "У двотисячному році"],
    ["3 червня 1999 року", "третього червня тисяча дев'ятсот дев'яносто дев'ятого року"],
    ["21 грудня", "двадцять першого грудня"],
    ["3-го червня", "третього червня"],
  ]);

  it("puts the stop back when the abbreviation ends the sentence", () => {
    expect(prepareUkrainian("Це було у 1861 р. Потім усе змінилося.")).toBe(
      "Це було у тисяча вісімсот шістдесят першому році. Потім усе змінилося.",
    );
  });
});

describe("Ukrainian centuries and chapters", () => {
  check([
    ["Це було в XIX столітті.", "Це було в дев'ятнадцятому столітті."],
    ["На початку XX століття.", "На початку двадцятого століття."],
    ["XXI століття почалося.", "двадцять перше століття почалося."],
    ["до XVIII століття", "до вісімнадцятого століття"],
    [
      "Наприкінці XIX століття і кінець XIX ст.",
      "Наприкінці дев'ятнадцятого століття і кінець дев'ятнадцятого століття.",
    ],
    ["У XIX ст. жили.", "У дев'ятнадцятому столітті жили."],
    ["У ХІХ столітті", "У дев'ятнадцятому столітті"], // Cyrillic Х and І
    ["Розділ IV", "Розділ четвертий"],
    ["розділ XII.", "розділ дванадцятий."],
    ["IV", "чотири"],
    ["XII.", "дванадцять."],
    ["II. Рік", "два. Рік"],
  ]);

  it("leaves letters that only look like numerals", () => {
    expect(prepareUkrainian("І він пішов. Мій друг Х прийшов.")).toBe(
      "І він пішов. Мій друг Х прийшов.",
    );
  });
});

describe("Ukrainian quantities", () => {
  check([
    ["15%", "п'ятнадцять відсотків"],
    ["1%", "один відсоток"],
    ["22%", "двадцять два відсотки"],
    ["3,5%", "три цілих п'ять десятих відсотка"],
    ["5 грн", "п'ять гривень"],
    ["1 грн", "одна гривня"],
    ["2 грн", "дві гривні"],
    ["12,50 грн.", "дванадцять гривень п'ятдесят копійок."],
    ["5 грн. Далі", "п'ять гривень. Далі"],
    ["Ціна 100 грн.", "Ціна сто гривень."],
    ["$5", "п'ять доларів"],
    ["10:30", "десять тридцять"],
    ["9:05", "дев'ять нуль п'ять"],
    ["10:00", "десять нуль нуль"],
  ]);
});

describe("Ukrainian numbers that are left", () => {
  check([
    ["3 книги", "три книги"],
    ["1 000 000 зірок", "один мільйон зірок"],
    ["1,5", "одна ціла п'ять десятих"],
    ["3.14", "три крапка чотирнадцять"],
    ["−5", "мінус п'ять"],
    ["5–10", "п'ять — десять"],
    ["№ 5", "номер п'ять"],
    ["007", "нуль нуль сім"],
    ["3-го", "третього"],
    ["1-му", "першому"],
    ["2020-го", "дві тисячі двадцятого"],
  ]);

  it("agrees 1 and 2 with the noun that follows", () => {
    expect(prepareUkrainian("1 книга і 21 книга")).toBe("одна книга і двадцять одна книга");
    expect(prepareUkrainian("2 години і 22 хвилини")).toBe("дві години і двадцять дві хвилини");
    expect(prepareUkrainian("21 яблуко, 1 питання")).toBe("двадцять одне яблуко, одне питання");
    expect(prepareUkrainian("1 або 2")).toBe("один або два");
    expect(prepareUkrainian("2 статті")).toBe("дві статті");
  });

  it("reads a long digit string digit by digit", () => {
    expect(prepareUkrainian("1234567890123")).toBe(
      "один два три чотири п'ять шість сім вісім дев'ять нуль один два три",
    );
  });
});

describe("Ukrainian abbreviations", () => {
  check([
    ["Це все, і т. д.", "Це все, і так далі."],
    ["Це все, і т. п. Далі.", "Це все, і таке інше. Далі."],
    ["Див. рис. 3.", "Дивіться рисунок три."],
    ["У м. Києві", "У місті Києві"],
    ["м. Львів", "місто Львів"],
    ["вул. ім. Франка", "вул. імені Франка"],
    ["Т. Г. Шевченко", "Т. Г. Шевченко"],
    ["і ін. та ін.", "і інші та інші."],
  ]);

  it("leaves 'м.' after a number alone", () => {
    expect(prepareUkrainian("5 м. Далі")).toBe("п'ять м. Далі");
  });
});

describe("Ukrainian voice alphabet", () => {
  check([
    ["дев’ятнадцятого", "дев'ятнадцятого"],
    ["Привіт… світе", "Привіт... світе"],
    ["«казка» і „байка“", "казка і байка"],
    ["він/вона", "він вона"],
    ["Одне (друге) третє", "Одне, друге, третє"],
    ["Harry Potter", "Гаррі Поттер"],
    ["York та Yes", "Йорк та Йес"],
    ["ёжик ыы эхо", "йожик ии ехо"],
  ]);

  it("keeps the capital of a name, for the sentence splitter", () => {
    expect(prepareUkrainian("Прийшов Charles. Він сів.")).toBe("Прийшов Чарлес. Він сів.");
  });
});
